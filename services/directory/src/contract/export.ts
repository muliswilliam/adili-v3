/**
 * Writes the directory's contract, packages/schemas/internal/directory.yaml: the service's
 * OpenAPI document (controllers' decorators + Zod schemas) plus the drafted operations of later
 * specs from packages/schemas/drafts/directory.yaml. CI runs this and fails when the committed
 * file differs, so the contract the console is generated from always matches the code.
 *
 *     pnpm --filter @adili/directory contracts
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

import { scanOpenApiDocument } from '@adili/api-kit';
import { parse, stringify } from 'yaml';

import { AppModule } from '../app.module.js';
import { SERVICE_DESCRIPTION, SERVICE_NAME } from '../config.js';
import { OPENAPI_SCHEMAS } from '../openapi.js';
import { type Draft, withDraft } from './draft.js';
import { readable } from './readable.js';

const SCHEMAS_PACKAGE = new URL('../../../../packages/schemas/', import.meta.url);
const DRAFT = fileURLToPath(new URL('drafts/directory.yaml', SCHEMAS_PACKAGE));
const OUTPUT = fileURLToPath(new URL('internal/directory.yaml', SCHEMAS_PACKAGE));

const HEADER = `# Generated by \`pnpm --filter @adili/directory contracts\`: do not edit.
# Implemented operations come from the directory service; operations marked \`x-draft\` come
# from packages/schemas/drafts/directory.yaml until they are implemented.
`;

const generated = await scanOpenApiDocument(AppModule, {
  name: SERVICE_NAME,
  description: SERVICE_DESCRIPTION,
  schemas: OPENAPI_SCHEMAS,
});

const document = readable(withDraft(generated, parse(readFileSync(DRAFT, 'utf8')) as Draft));
const yaml =
  HEADER + stringify(document, { lineWidth: 0, aliasDuplicateObjects: false, singleQuote: true });
writeFileSync(OUTPUT, yaml);
console.log(`wrote ${OUTPUT}`);
